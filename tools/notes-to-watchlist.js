/**
 * Generate a BizHawk watchlist from a RetroAchievements code notes file.
 *
 * Usage:
 *   node tools/notes-to-watchlist.js lua-script/5260-Notes.json > lua-script/watchlist.lua
 *   node tools/notes-to-watchlist.js lua-script/5260-Notes.json --grep 'ranking|state'
 *   node tools/notes-to-watchlist.js lua-script/5260-Notes.json --json
 *
 * The generated watchlist.lua is picked up automatically by
 * lua-script/record_scenario.lua. Sizes come from the "[8-bit]"/"[16-bit]"/
 * "[32-bit]" tags in the notes (default 8-bit); big-endian sizes record the
 * same raw little-endian bytes - the trigger runtime applies the BE
 * interpretation itself.
 */

import { readFileSync } from 'node:fs';
import { parseCodeNotes, codeNotesToWatchlist } from '../src/code-notes.js';

const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith('--'));
if (!file) {
  console.error('usage: node tools/notes-to-watchlist.js <notes.txt> [--grep <regex>] [--json]');
  process.exit(1);
}

const grepIndex = args.indexOf('--grep');
const grep = grepIndex >= 0 ? new RegExp(args[grepIndex + 1], 'i') : null;
const asJson = args.includes('--json');

let notes = parseCodeNotes(readFileSync(file, 'utf8'));
if (grep) notes = notes.filter((n) => grep.test(n.label));

const watchlist = codeNotesToWatchlist(notes).map((entry, i) => ({
  ...entry,
  label: notes[i].label,
}));

if (asJson) {
  console.log(JSON.stringify(watchlist, null, 2));
} else {
  const luaEscape = (s) => s.replace(/[\\"]/g, '\\$&');
  console.log('-- generated by tools/notes-to-watchlist.js from ' + file);
  console.log('return {');
  for (const { address, size, label } of watchlist) {
    console.log(`    { address = 0x${address.toString(16).padStart(4, '0')}, size = "${size}", label = "${luaEscape(label)}" },`);
  }
  console.log('}');
}

console.error(`${watchlist.length} addresses`);
